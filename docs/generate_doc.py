def add_heading(doc, text, level):
    heading = doc.add_heading(text, level=level)
    for run in heading.runs:
        run.font.name = 'Arial'
        if level == 1:
            run.font.color.rgb = None

def main():
    doc = Document()
    
    # Title
    title = doc.add_heading('OmniGeneDB System Documentation', 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    
    doc.add_paragraph("A Cloud-Native Bioinformatics & Systems Biology Platform").alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph("Generated by Antigravity AI").alignment = WD_ALIGN_PARAGRAPH.CENTER
    
    doc.add_page_break()

    # Introduction
    add_heading(doc, '1. Introduction', 1)
    doc.add_paragraph(
        "OmniGeneDB is an advanced, automated bioinformatics web application designed for multi-omics "
        "profiling and systems biology analysis. It streamlines the complex workflow of fetching "
        "raw RNA-seq count matrices from the NCBI Gene Expression Omnibus (GEO), running rigorous "
        "statistical differential expression (DESeq2), and integrating the results across numerous "
        "biological databases to provide actionable, translational insights."
    )
    
    # Features
    add_heading(doc, '2. Core Features', 1)
    
    add_heading(doc, '2.1 Automated Differential Expression', 2)
    doc.add_paragraph(
        "By simply providing a valid GEO Accession (e.g., GSE270967) and specifying Case/Control group metadata, "
        "OmniGeneDB automatically downloads the count matrices, builds a clinical design matrix, and executes "
        "a highly parallelized DESeq2 R pipeline in the backend. It ranks the entire transcriptome by statistical "
        "significance (padj) and fold change."
    )
    
    add_heading(doc, '2.2 Advanced Systems Biology Visualizations', 2)
    doc.add_paragraph(
        "- Volcano & PCA Plots: Standard high-quality scatter plots to evaluate dataset variance and gene significance.\n"
        "- Immune Deconvolution: Uses MCPcounter to dynamically estimate the absolute abundance of 8 immune cell "
        "populations and 2 stromal populations, rendered as interactive stacked bar charts.\n"
        "- Gene Set Enrichment Analysis (GSEA): Maps the transcriptome to Gene Ontology (GO) and KEGG pathways "
        "to highlight macro-level biological shifts.\n"
        "- STRING PPI Networks: An interactive 2D physics-based network graph visualizing known protein-protein "
        "interactions among the top differentially expressed genes."
    )
    
    add_heading(doc, '2.3 Multi-Omics API Integrations', 2)
    doc.add_paragraph(
        "The Top Differentially Expressed Genes (DEG) table is enriched with live API data:\n"
        "- OpenTargets: Fetches known clinical drugs and clinical candidates targeting the gene.\n"
        "- GTEx: Retrieves known expression quantitative trait loci (eQTLs) for the gene across human tissues.\n"
        "- ClinVar: Pulls counts of known pathogenic clinical variants associated with the gene.\n"
        "- Structural Biology: Links out to the AlphaFold 3D database and PDB (Protein Data Bank) structural viewers."
    )
    
    add_heading(doc, '2.4 Cloud-Native Deployment', 2)
    doc.add_paragraph(
        "OmniGeneDB is containerized via multi-stage Dockerfiles. The frontend is a React 19 + Vite SPA served "
        "by Nginx, while the backend is a Python FastAPI wrapper around an embedded R/Bioconductor 3.18 runtime. "
        "The system is deployed on Google Cloud Run with Google Cloud Storage FUSE for zero-downtime persistent "
        "database scaling."
    )

    # Workflow
    add_heading(doc, '3. End-to-End Workflow', 1)
    doc.add_paragraph(
        "1. Data Ingestion: The user inputs a GEO accession. The Python backend scrapes NCBI to auto-suggest metadata groups.\n"
        "2. Pipeline Execution: The user submits the form. The backend spins up an R subprocess, downloads the counts via GEOquery, "
        "formats the DESeq2 design matrix, and runs the Wald test.\n"
        "3. Integration Phase: The Python API takes the top N genes from the DESeq2 results and fires parallel GraphQL/REST queries "
        "to STRING, GTEx, OpenTargets, and ClinVar.\n"
        "4. Rendering: The React frontend fetches the final JSON payload and renders all interactive Recharts charts, D3 force graphs, "
        "and data tables.\n"
        "5. Persistence: The results are saved to a persistent SQLite database (mounted via GCP Cloud Storage) for instantaneous "
        "future retrieval."
    )
    
    # Limitations
    add_heading(doc, '4. System Limitations & Guardrails', 1)
    doc.add_paragraph(
        "- Microarray Incompatibility: OmniGeneDB relies on raw RNA-seq count matrices. It strictly guards against and rejects "
        "Microarray (e.g., Affymetrix/Illumina) datasets, as they require specialized CEL probe-to-gene mapping pipelines.\n"
        "- Multi-Omics Mixed Cohorts: If a GEO accession contains a mix of RNA-seq and ATAC-seq/WGBS samples under the same metadata "
        "labels, the system will drop the non-RNA-seq samples. If this results in 0 samples for a group, the pipeline will fail gracefully.\n"
        "- API Rate Limits: External integrations (STRING, GTEx) are subject to public API rate limits. In the event of a timeout, "
        "the specific column will gracefully degrade to 'N/A' rather than crashing the UI.\n"
        "- Cloud Run Cold Starts: Because the backend Docker container contains a massive R Bioconductor environment (3GB+), "
        "the first request after a long period of inactivity may experience a 10-15 second cold start delay on Google Cloud Run."
    )

    doc.save('OmniGeneDB_Documentation.docx')
    print("Document saved as OmniGeneDB_Documentation.docx")

if __name__ == '__main__':
    main()
